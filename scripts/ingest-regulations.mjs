import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, extname, join, resolve } from 'node:path';
import * as pdfjs from '../compliance-drift/node_modules/pdfjs-dist/legacy/build/pdf.mjs';

const root = resolve('data/au-regulations');
const output = resolve('src/assistant/regulations.generated.js');
const publicDocs = resolve('compliance-drift/public/docs');

const META = [
  [/AER-Retail-Law/i, 'aer-2026', 'AER (Retail Law) Instrument 2026', 'General · AER instrument · NERL states'],
  [/Best-Offer/i, 'best-offer', 'Best Offer Policy v2.1', 'VIC only · Energy Retail Code'],
  [/Billing-Accuracy/i, 'billing-std', 'Billing Accuracy Standard v3.0', 'General · NERR-derived'],
  [/Customer-Hardship/i, 'hardship-policy', 'Customer Hardship Policy Rev 4', 'General · AER-approved retailer policy'],
  [/Energy Retail Code/i, 'energy-retail-code-v6', 'Energy Retail Code of Practice v6', 'Victoria · Essential Services Commission'],
  [/FDV-Policy/i, 'fdv-policy', 'Family and Domestic Violence Policy Rev 2', 'General · all retail jurisdictions'],
  [/Guideline-Payment Difficulty/i, 'payment-difficulty-guideline-2026', 'Payment Difficulty Framework Guideline · 1 October 2026', 'Victoria · Essential Services Commission'],
  [/NERR/i, 'nerr', 'National Energy Retail Rules v51', 'General · AER · NERL states'],
  [/WI-4-Credit/i, 'wi-4', 'Credit & Collections Work Instruction v11', 'Internal control · state overlays apply'],
];

function metadata(file) {
  const match = META.find(([pattern]) => pattern.test(file));
  if (!match) return null;
  return { id: match[1], title: match[2], scope: match[3] };
}

function canonicalFile(file, id) {
  return id === 'nerr' ? 'NERR-v51.pdf' : file;
}

function cleanText(items) {
  let text = '';
  for (const item of items) {
    if (!('str' in item)) continue;
    text += item.str;
    text += item.hasEOL ? '\n' : ' ';
  }
  return text
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .replace(/[ \t]{2,}/g, ' ')
    .trim();
}

mkdirSync(publicDocs, { recursive: true });
const seen = new Set();
const documents = [];

for (const file of readdirSync(root).filter((name) => extname(name).toLowerCase() === '.pdf').sort()) {
  const source = join(root, file);
  const bytes = readFileSync(source);
  const hash = createHash('sha256').update(bytes).digest('hex');
  if (seen.has(hash)) continue;
  seen.add(hash);

  const meta = metadata(file);
  if (!meta) continue;
  const targetFile = canonicalFile(file, meta.id);
  copyFileSync(source, join(publicDocs, targetFile));

  const pdf = await pdfjs.getDocument({ data: new Uint8Array(bytes), disableWorker: true }).promise;
  const sections = [];
  for (let pageNumber = 1; pageNumber <= pdf.numPages; pageNumber += 1) {
    const page = await pdf.getPage(pageNumber);
    const content = await page.getTextContent();
    const text = cleanText(content.items);
    if (text) sections.push({ page: pageNumber, ref: `p. ${pageNumber}`, text });
  }

  documents.push({ ...meta, file: targetFile, pages: pdf.numPages, hash, sections });
}

const banner = '// Generated by scripts/ingest-regulations.mjs. Do not edit by hand.\n';
writeFileSync(output, `${banner}export default ${JSON.stringify(documents, null, 2)};\n`, 'utf8');
console.log(`Ingested ${documents.length} unique PDFs and ${documents.reduce((sum, doc) => sum + doc.sections.length, 0)} text pages.`);
console.log(`Wrote ${output}`);
